/* ── Small maths ───────────────────────────────────────────────────────── */
const clamp  = (v, a, b) => Math.max(a, Math.min(b, v));
const lerp   = (a, b, t) => a + (b - a) * t;
const smooth = t => { t = clamp(t, 0, 1); return t * t * (3 - 2 * t); };
const easeIO = t => { t = clamp(t, 0, 1); return t < .5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2; };
const easeOut = t => 1 - Math.pow(1 - clamp(t, 0, 1), 3);

// Radius of the circle centred on (cx,cy) that covers the whole viewport —
// what the intro veil needs to grow to before it can hold the screen.
function coverRadius(cx, cy, w, h){
  return Math.max(
    Math.hypot(cx, cy), Math.hypot(w - cx, cy),
    Math.hypot(cx, h - cy), Math.hypot(w - cx, h - cy)
  );
}

const reduceMotion = () => window.matchMedia('(prefers-reduced-motion: reduce)').matches;

function useMedia(query){
  const [match, setMatch] = useState(() => window.matchMedia(query).matches);
  useEffect(() => {
    const mq = window.matchMedia(query);
    const on = e => setMatch(e.matches);
    mq.addEventListener('change', on);
    setMatch(mq.matches);
    return () => mq.removeEventListener('change', on);
  }, [query]);
  return match;
}

/* ── Routing ───────────────────────────────────────────────────────────────
   Real paths, not hashes: /work/, /work/f1/, /about/, /contact/. Every one of
   them is a real file on the server (generated by tools/build.mjs), so a
   shared link previews with the right title and image. Old #/work/f1 links
   are rewritten to the new form on boot (see index.html). */
function parsePath(pathname){
  const parts = String(pathname || '/').replace(/^\/+|\/+$/g, '').split('/').filter(Boolean);
  if (!parts.length) return { route: 'home', sub: '' };
  const r = parts[0].toLowerCase();
  if (r === 'work')    return { route: 'work', sub: (parts[1] || '').toLowerCase() };
  if (r === 'about')   return { route: 'about', sub: '' };
  if (r === 'contact') return { route: 'contact', sub: '' };
  return { route: '404', sub: '' };
}
const pathFor     = (route, sub) => route === 'home' ? '/' : '/' + route + (sub ? '/' + sub : '') + '/';
const projectPath = id => '/work/' + id + '/';

// An <a> that navigates in-app on a plain left click, and behaves like a
// normal link for everything else (new tab, middle click, crawlers).
function Link({ to, children, className, onClick, ...rest }){
  return (
    <a href={to} className={className} {...rest}
       onClick={e => {
         if (onClick) onClick(e);
         if (e.defaultPrevented) return;
         if (e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
         if (rest.target === '_blank') return;
         e.preventDefault();
         if (window.__nav) window.__nav(to);
       }}>
      {children}
    </a>
  );
}

// Smooth scroll that goes through Lenis when it is running.
function scrollToEl(el, offset){
  if (!el) return;
  const off = offset == null ? -84 : offset;
  if (window.__lenis) { window.__lenis.scrollTo(el, { offset: off, duration: 1.1 }); return; }
  const y = el.getBoundingClientRect().top + window.scrollY + off;
  window.scrollTo({ top: y, behavior: reduceMotion() ? 'instant' : 'smooth' });
}

/* ── Time ──────────────────────────────────────────────────────────────── */
function brusselsTime(){
  try {
    return new Intl.DateTimeFormat('en-GB', { hour: '2-digit', minute: '2-digit', hour12: false, timeZone: 'Europe/Brussels' }).format(new Date());
  } catch (e) {
    return new Intl.DateTimeFormat('en-GB', { hour: '2-digit', minute: '2-digit', hour12: false }).format(new Date());
  }
}
function useClock(){
  const [t, setT] = useState(brusselsTime);
  useEffect(() => {
    const id = setInterval(() => setT(brusselsTime()), 30000);
    return () => clearInterval(id);
  }, []);
  return t;
}

// Live age from an ISO date of birth ("YYYY-MM-DD").
function computeAge(birth){
  const d = new Date(birth);
  if (isNaN(d.getTime())) return null;
  const now = new Date();
  let a = now.getFullYear() - d.getFullYear();
  const m = now.getMonth() - d.getMonth();
  if (m < 0 || (m === 0 && now.getDate() < d.getDate())) a--;
  return a;
}

/* ── Project dates ─────────────────────────────────────────────────────── */
function parseProjDate(s){
  if (!s) return null;
  let str = String(s).trim();
  if (/^\d{4}-\d{2}$/.test(str)) str += '-01';
  const t = Date.parse(str);
  return isNaN(t) ? null : new Date(t);
}
function projDateLabel(p){
  const d = parseProjDate(p.date);
  if (d){
    const hasDay = /^\d{4}-\d{2}-\d{2}/.test(String(p.date).trim());
    return d.toLocaleDateString('en-GB', { day: hasDay ? 'numeric' : undefined, month: 'short', year: 'numeric', timeZone: 'UTC' });
  }
  return p.year || '';
}
function projDateKey(p){
  const d = parseProjDate(p.date);
  if (d) return d.getTime();
  const yrs = String(p.year || '').match(/\d{4}/g);
  const y = yrs ? Math.max.apply(null, yrs.map(Number)) : 0;
  return y ? Date.UTC(y, 11, 31) : 0;
}
// The span of years covered by the projects, for the Work page eyebrow.
function projectYears(){
  const ys = PROJS().map(p => new Date(projDateKey(p)).getUTCFullYear()).filter(Boolean);
  if (!ys.length) return '';
  const lo = Math.min.apply(null, ys), hi = Math.max.apply(null, ys);
  return lo === hi ? String(lo) : lo + ' — ' + hi;
}

/* ── Timeline periods ───────────────────────────────────────────────────
   "2025-09 — Present", "2022-09 — 2025-06", "Fall 2026" … Only an em/en dash
   surrounded by spaces separates the two sides, so ISO dates stay intact. */
const PERIOD_SPLIT = /\s+[—–]\s+/;
function formatPeriodPart(s){
  s = String(s).trim();
  if (/^\d{4}-\d{2}-\d{2}$/.test(s)) return new Date(s + 'T00:00:00Z').toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });
  if (/^\d{4}-\d{2}$/.test(s))       return new Date(s + '-01T00:00:00Z').toLocaleDateString('en-GB', { month: 'short', year: 'numeric', timeZone: 'UTC' });
  return s;
}
const formatPeriod = period => String(period || '').split(PERIOD_SPLIT).map(formatPeriodPart).join(' — ');
function periodStartKey(period){
  const first = String(period || '').split(PERIOD_SPLIT)[0].trim();
  if (/^\d{4}-\d{2}-\d{2}$/.test(first)) return Date.parse(first + 'T00:00:00Z');
  if (/^\d{4}-\d{2}$/.test(first))       return Date.parse(first + '-01T00:00:00Z');
  const m = first.match(/\d{4}/);
  return m ? Date.UTC(+m[0], 0, 1) : 0;
}
function periodEndKey(period){
  const parts = String(period || '').split(PERIOD_SPLIT);
  const last  = (parts[parts.length - 1] || '').trim();
  if (parts.length < 2 || /present|now|today|ongoing/i.test(last)) return Date.now();
  if (/^\d{4}-\d{2}-\d{2}$/.test(last)) return Date.parse(last + 'T00:00:00Z');
  if (/^\d{4}-\d{2}$/.test(last)){
    const d = new Date(last + '-01T00:00:00Z');
    return Date.UTC(d.getUTCFullYear(), d.getUTCMonth() + 1, 0);   // end of that month
  }
  const m = last.match(/\d{4}/);
  if (m) return Date.UTC(+m[0], 11, 31);
  return periodStartKey(period) + 90 * 864e5;
}
// The timeline entries, oldest first, with their real start/end in ms.
function timelineEntries(){
  const now = Date.now();
  return (PROFILE().timeline || []).map(e => {
    const start = periodStartKey(e.period);
    let end = periodEndKey(e.period);
    if (end < start) end = start + 30 * 864e5;
    return Object.assign({}, e, { start, end, upcoming: start > now, current: start <= now && now <= end });
  }).sort((a, b) => a.start - b.start);
}

/* ── CV files ───────────────────────────────────────────────────────────
   data.js may declare one PDF per language; a language whose file is missing
   from /assets/cv is dropped from the menu, so the site follows the files you
   actually ship. Probing fails open (offline, file://) — a link is never
   hidden by accident. */
const CV_LANGS = [['en', 'English'], ['fr', 'Français'], ['nl', 'Nederlands']];
function cvDeclared(P){
  const cv = (P || {}).cv;
  if (!cv) return [];
  if (typeof cv === 'string') return (cv && cv !== '#') ? [{ lang: 'en', label: 'CV', href: cv }] : [];
  return CV_LANGS.map(([lang, label]) => (cv[lang] && cv[lang] !== '#') ? { lang, label, href: cv[lang] } : null).filter(Boolean);
}
const cvFound  = new Map();
const cvProbes = new Map();
function cvProbe(href){
  if (cvProbes.has(href)) return cvProbes.get(href);
  const sameOrigin = !/^[a-z]+:\/\//i.test(href) && !href.startsWith('//');
  const canProbe = sameOrigin && typeof fetch === 'function' && typeof location !== 'undefined' && location.protocol !== 'file:';
  const p = (canProbe ? fetch(href, { method: 'HEAD' }).then(r => r.ok).catch(() => true) : Promise.resolve(true))
    .then(ok => { cvFound.set(href, ok); return ok; });
  cvProbes.set(href, p);
  return p;
}
const cvLinks = P => cvDeclared(P).filter(c => cvFound.get(c.href) !== false);
function cvLinksReady(P){
  const declared = cvDeclared(P);
  return Promise.all(declared.map(c => cvProbe(c.href))).then(ok => declared.filter((c, i) => ok[i]));
}
function cvPrimary(P){ const l = cvLinks(P); return l.length ? l[0].href : null; }
function useCvLinks(){
  const P = PROFILE();
  const [links, setLinks] = useState(() => cvLinks(P));
  useEffect(() => {
    let alive = true;
    cvLinksReady(P).then(l => { if (alive) setLinks(l); });
    return () => { alive = false; };
  }, []);
  return links;
}


function projAttachments(p){
  return (Array.isArray(p.attachments) ? p.attachments : [])
    .map(a => typeof a === 'string' ? { url: a } : a)
    .map(a => Object.assign({}, a, { url: (a && (a.url || a.file)) || '' }))
    .filter(a => a.url && a.url !== '#')
    .map(a => {
      const clean = a.url.split(/[?#]/)[0];
      const ext   = (clean.match(/\.([a-z0-9]+)$/i) || [])[1] || '';
      const key   = String(a.type || ext).toLowerCase();
      const kind  = ATT_TYPES[key] || (a.type ? a.type : 'Link');
      return {
        url: a.url,
        label: a.label || decodeURIComponent(clean.split('/').pop()) || kind,
        note: a.note || '',
        kind,
        icon: ATT_ICONS[kind] || 'FileLink',
        local: !/^(https?:)?\/\//i.test(a.url),
      };
    });
}

/* ── Text helpers ──────────────────────────────────────────────────────────
   In data.js, *asterisks* set a few words in the italic serif — the "voice"
   of the charter. Used by the home intro. */
function emphasise(text){
  return String(text || '').split(/\*([^*]+)\*/g).map((chunk, i) => {
    if (!chunk) return null;
    return i % 2 ? <em key={i}>{chunk}</em> : <React.Fragment key={i}>{chunk}</React.Fragment>;
  });
}
// Same string, but as one span per word so the scroll can fill them in turn.
function fillWords(text){
  const out = [];
  String(text || '').split(/\*([^*]+)\*/g).forEach((chunk, i) => {
    if (!chunk) return;
    const em = i % 2 === 1;
    chunk.split(/\s+/).filter(Boolean).forEach(w => out.push({ w, em }));
  });
  return out;
}

/* ── Reveals ───────────────────────────────────────────────────────────────
   Anything with .rv gets .in the first time it enters the viewport; the CSS
   does the rest. With reduced motion (or no observer) everything is shown at
   once — the page never depends on the animation to be readable. */
function useReveals(rootRef, deps){
  useEffect(() => {
    const root = (rootRef && rootRef.current) || document.body;
    const els = Array.prototype.slice.call(root.querySelectorAll('.rv:not(.in)'));
    if (!els.length) return;
    if (reduceMotion() || typeof IntersectionObserver === 'undefined'){
      els.forEach(el => el.classList.add('in'));
      return;
    }
    const io = new IntersectionObserver(entries => {
      entries.forEach(en => { if (en.isIntersecting){ en.target.classList.add('in'); io.unobserve(en.target); } });
    }, { rootMargin: '0px 0px -10% 0px', threshold: 0 });
    els.forEach(el => io.observe(el));
    return () => io.disconnect();
  }, deps || []);
}

// One rAF-throttled callback for scroll + resize, run once on mount.
function useScrollFrame(fn, deps){
  useEffect(() => {
    let raf = 0;
    const run = () => { raf = 0; fn(); };
    const schedule = () => { if (!raf) raf = requestAnimationFrame(run); };
    run();
    window.addEventListener('scroll', schedule, { passive: true });
    window.addEventListener('resize', schedule);
    return () => {
      window.removeEventListener('scroll', schedule);
      window.removeEventListener('resize', schedule);
      if (raf) cancelAnimationFrame(raf);
    };
  }, deps || []);
}


const CARD_SIZES = {
  lg: '(max-width:720px) calc(100vw - 2 * clamp(24px,4.6vw,48px)), (max-width:1360px) 46vw, 610px',
  sm: '(max-width:560px) calc(100vw - 2 * clamp(24px,4.6vw,48px)), (max-width:980px) 46vw, 400px',
};

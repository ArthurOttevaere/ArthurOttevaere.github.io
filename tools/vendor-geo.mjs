/* =================================================================
   vendor-geo.mjs — copies what the World page needs out of node_modules.

   WHAT IT WRITES
     assets/vendor/geo.min.js       d3-array + d3-geo + topojson-client,
                                    in one file (one request). They are
                                    UMD builds and hang themselves on
                                    window.d3 and window.topojson.
     assets/map/countries-110m.json Natural Earth 1:110m (world-atlas).
                                    The whole globe, loaded with the page.
     assets/map/countries-50m.json  Natural Earth 1:50m. Only fetched the
                                    first time someone zooms in, so the
                                    coasts stay sharp up close.

   Natural Earth is public domain; d3 and topojson are ISC; the licence
   lines are kept at the top of geo.min.js.

   USAGE
     npm run geo        (after `npm install`, or after bumping a version)
   ================================================================= */

import { readFile, writeFile, copyFile, mkdir } from 'node:fs/promises';

const LIBS = [
  ['d3-array',        'node_modules/d3-array/dist/d3-array.min.js'],
  ['d3-geo',          'node_modules/d3-geo/dist/d3-geo.min.js'],
  ['topojson-client', 'node_modules/topojson-client/dist/topojson-client.min.js'],
];

const version = async name => JSON.parse(await readFile(`node_modules/${name}/package.json`, 'utf8')).version;

await mkdir('assets/vendor', { recursive: true });
await mkdir('assets/map', { recursive: true });

let out = '/* World page geography — generated by tools/vendor-geo.mjs, do not edit.\n';
for (const [name] of LIBS) out += `   ${name}@${await version(name)} · ISC licence\n`;
out += '*/\n';
for (const [name, file] of LIBS) out += `/* ${name} */\n` + (await readFile(file, 'utf8')).trim() + '\n';
await writeFile('assets/vendor/geo.min.js', out);
console.log(`✓ assets/vendor/geo.min.js (${(out.length / 1024).toFixed(1)} KB)`);

for (const res of ['110m', '50m']){
  await copyFile(`node_modules/world-atlas/countries-${res}.json`, `assets/map/countries-${res}.json`);
  console.log(`✓ assets/map/countries-${res}.json`);
}
